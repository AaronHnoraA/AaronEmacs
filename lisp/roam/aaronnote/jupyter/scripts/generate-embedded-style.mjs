import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import postcss from "postcss";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const aaronnoteRoot = resolve(scriptDir, "../..");
const sources = [
  resolve(aaronnoteRoot, "src/styles/widgets.css"),
  resolve(aaronnoteRoot, "src/styles/theme-typora.css"),
];
const output = resolve(aaronnoteRoot, "jupyter/labextension/style/aaronnote-embedded.css");
const scope = ".cm-editor.aaronnote-embedded-markdown";

function insideKeyframes(rule) {
  let parent = rule.parent;
  while (parent) {
    if (parent.type === "atrule" && /keyframes$/i.test(parent.name)) return true;
    parent = parent.parent;
  }
  return false;
}

function scopeSelector(selector) {
  const trimmed = selector.trim();
  if (!trimmed) return trimmed;
  if (trimmed.includes(".cm-editor")) {
    return trimmed.replaceAll(".cm-editor", scope);
  }
  if (trimmed === ":root") return scope;
  return `${scope} ${trimmed}`;
}

const css = (await Promise.all(sources.map((source) => readFile(source, "utf8")))).join("\n");
const root = postcss.parse(css);
root.walkRules((rule) => {
  if (insideKeyframes(rule)) return;
  rule.selectors = rule.selectors.map(scopeSelector);
});

await writeFile(
  output,
  `/* Generated by jupyter/scripts/generate-embedded-style.mjs. */\n${root.toString()}\n`,
  "utf8",
);
